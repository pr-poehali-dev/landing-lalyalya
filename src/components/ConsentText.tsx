interface ConsentTextProps {
  className?: string;
  checked?: boolean;
  onCheckedChange?: (checked: boolean) => void;
}

const ConsentText = ({ className, checked, onCheckedChange }: ConsentTextProps) => {
  const [showOffer, setShowOffer] = useState(false);
  const [showPrivacy, setShowPrivacy] = useState(false);

  const withCheckbox = onCheckedChange !== undefined;

  const text = (
    <span className={withCheckbox ? undefined : className ?? 'text-xs leading-relaxed text-muted-foreground'}>
      Отправляя заявку, я подтверждаю, что ознакомлен(а) и согласен(а) с условиями{' '}
      <button
        type="button"
        onClick={(e) => {
          e.preventDefault();
          setShowOffer(true);
        }}
        className="font-semibold text-accent underline hover:opacity-80"
      >
        Договора-оферты
      </button>{' '}
      и{' '}
      <button
        type="button"
        onClick={(e) => {
          e.preventDefault();
          setShowPrivacy(true);
        }}
        className="font-semibold text-accent underline hover:opacity-80"
      >
        Политики конфиденциальности
      </button>
      , а также даю согласие на обработку моих персональных данных.
    </span>
  );

  return (
    <>
      {withCheckbox ? (
        <label className={className ?? 'flex cursor-pointer items-start gap-3'}>
          <Checkbox
            checked={checked}
            onCheckedChange={(v) => onCheckedChange?.(v === true)}
            className="mt-1 shrink-0"
          />
          <span className="text-xs leading-relaxed text-muted-foreground">{text}</span>
        </label>
      ) : (
        <p className={className ?? 'text-xs leading-relaxed text-muted-foreground'}>{text}</p>
      )}

      <Dialog open={showOffer} onOpenChange={setShowOffer}>
        <DialogContent className="max-h-[85vh] max-w-2xl overflow-y-auto">
          <DialogHeader>
            <DialogTitle className="font-display text-2xl">Договор-оферта</DialogTitle>
          </DialogHeader>
          <OfferText />
        </DialogContent>
      </Dialog>

      <Dialog open={showPrivacy} onOpenChange={setShowPrivacy}>
        <DialogContent className="max-h-[85vh] max-w-2xl overflow-y-auto">
          <DialogHeader>
            <DialogTitle className="font-display text-2xl">
              Политика конфиденциальности
            </DialogTitle>
          </DialogHeader>
          <PrivacyPolicyText />
        </DialogContent>
      </Dialog>
    </>
  );
};

